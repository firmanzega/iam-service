-- Multi-tenancy: tenant_id on core tables.
--
-- Kenapa pendekatan dua tahap (nullable dulu, backfill, baru NOT NULL):
--   - Tabel inti sudah berisi data. Kolom NOT NULL tanpa default akan
--     gagal diterapkan, dan PostgreSQL tidak mendukung subquery di DEFAULT.
--   - Tenant default dibuat terlebih dahulu, lalu semua baris existing
--     di-backfill ke tenant itu sebelum constraint NOT NULL ditetapkan.
--   - Tabel roles sengaja tidak diberikan tenant_id: role master
--     (ADMIN, USER, AUDITOR, MANAGER) tetap global untuk menghindari
--     replikasi per tenant (lihat ADR 0016 bab 6.2).

CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    organization_id VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- 1. Tambah kolom tenant_id (belum NOT NULL karena tabel sudah berisi data)
ALTER TABLE users ADD COLUMN tenant_id BIGINT;
ALTER TABLE sessions ADD COLUMN tenant_id BIGINT;
ALTER TABLE refresh_tokens ADD COLUMN tenant_id BIGINT;
ALTER TABLE audit_logs ADD COLUMN tenant_id BIGINT;
ALTER TABLE security_rejection_stats ADD COLUMN tenant_id BIGINT;

-- 2. Buat tenant default untuk data existing
INSERT INTO tenants (name, organization_id)
VALUES ('Default Tenant', 'org-default')
ON CONFLICT (organization_id) DO NOTHING;

-- 3. Backfill semua baris existing ke tenant default
UPDATE users SET tenant_id = (SELECT id FROM tenants WHERE organization_id = 'org-default');
UPDATE sessions SET tenant_id = (SELECT id FROM tenants WHERE organization_id = 'org-default');
UPDATE refresh_tokens SET tenant_id = (SELECT id FROM tenants WHERE organization_id = 'org-default');
UPDATE audit_logs SET tenant_id = (SELECT id FROM tenants WHERE organization_id = 'org-default');
UPDATE security_rejection_stats SET tenant_id = (SELECT id FROM tenants WHERE organization_id = 'org-default');

-- 4. Terapkan NOT NULL dan FK constraint
ALTER TABLE users ALTER COLUMN tenant_id SET NOT NULL;
ALTER TABLE sessions ALTER COLUMN tenant_id SET NOT NULL;
ALTER TABLE refresh_tokens ALTER COLUMN tenant_id SET NOT NULL;
ALTER TABLE audit_logs ALTER COLUMN tenant_id SET NOT NULL;
ALTER TABLE security_rejection_stats ALTER COLUMN tenant_id SET NOT NULL;

ALTER TABLE users ADD CONSTRAINT fk_users_tenant_id FOREIGN KEY (tenant_id) REFERENCES tenants(id);
ALTER TABLE sessions ADD CONSTRAINT fk_sessions_tenant_id FOREIGN KEY (tenant_id) REFERENCES tenants(id);
ALTER TABLE refresh_tokens ADD CONSTRAINT fk_refresh_tokens_tenant_id FOREIGN KEY (tenant_id) REFERENCES tenants(id);
ALTER TABLE audit_logs ADD CONSTRAINT fk_audit_logs_tenant_id FOREIGN KEY (tenant_id) REFERENCES tenants(id);
ALTER TABLE security_rejection_stats ADD CONSTRAINT fk_security_rejection_stats_tenant_id FOREIGN KEY (tenant_id) REFERENCES tenants(id);

-- 5. Index untuk tenant-scoped queries
CREATE INDEX idx_users_tenant_id ON users(tenant_id);
CREATE INDEX idx_sessions_tenant_id ON sessions(tenant_id);
CREATE INDEX idx_refresh_tokens_tenant_id ON refresh_tokens(tenant_id);
CREATE INDEX idx_audit_logs_tenant_id ON audit_logs(tenant_id);
CREATE INDEX idx_security_rejection_stats_tenant_id ON security_rejection_stats(tenant_id);

COMMENT ON TABLE tenants IS
    'Organisasi tenant. Internal tenant_id digunakan di seluruh tabel inti untuk isolasi logis.';
COMMENT ON COLUMN tenants.organization_id IS
    'Identitas organisasi yang diekspos eksternal lewat header X-Organization-ID.';
COMMENT ON COLUMN users.tenant_id IS
    'Tenant pemilik pengguna. Semua query pengguna difilter oleh tenant ini.';
COMMENT ON COLUMN sessions.tenant_id IS
    'Tenant pemilik sesi perangkat.';
COMMENT ON COLUMN refresh_tokens.tenant_id IS
    'Tenant pemilik token refresh.';
COMMENT ON COLUMN audit_logs.tenant_id IS
    'Tenant tempat jejak audit dicatat.';
COMMENT ON COLUMN security_rejection_stats.tenant_id IS
    'Tenant tempat agregat penolakan 401 dicatat.';
