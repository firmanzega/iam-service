-- Sesi per perangkat dan agregat penolakan 401.
--
-- Kenapa sesi dipisahkan dari refresh_tokens:
--   - Satu sesi bisa melewati banyak rotasi token refresh. Kalau sesi
--     disimpan sebagai kolom di setiap token, daftar perangkat harus
--     mengelompokkan ulang baris token, dan pencabutan satu perangkat
--     berarti menebak token mana yang termasuk di dalamnya.
--   - Tabel sendiri memberi identitas yang stabil: token membawa session_id,
--     dan pencabutan cukup menandai satu baris sesi beserta token turunannya.
--
-- Kenapa session_id boleh NULL:
--   - Token yang terbit sebelum pembaruan ini tidak punya sesi. Masa
--     berlakunya paling lama 7 hari, jadi keadaan itu sementara. Token lama
--     tetap bisa ditukar; sesi baru dibuat saat penukaran berikutnya.

CREATE TABLE sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_label VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_sessions_user_id ON sessions(user_id);
CREATE INDEX idx_sessions_last_seen_at ON sessions(last_seen_at);

ALTER TABLE refresh_tokens ADD COLUMN session_id UUID;

ALTER TABLE refresh_tokens
    ADD CONSTRAINT refresh_tokens_session_id_fkey
    FOREIGN KEY (session_id) REFERENCES sessions(id) ON DELETE CASCADE;

CREATE INDEX idx_refresh_tokens_session_id ON refresh_tokens(session_id);

-- Agregat penolakan 401.
--
-- Kenapa tidak menyimpan path atau alamat IP:
--   - Keduanya dikendalikan pemanggil. Penyerang bisa mengirim path acak
--     sehingga jumlah baris tumbuh tanpa batas dalam satu menit. Agregat
--     yang bisa digelembungkan bukan alat pemantauan yang berguna.
--   - Alamat IP adalah data pribadi. Menyimpannya menuntut kebijakan retensi
--     dan dasar pemrosesan tersendiri, sedangkan volume penolakan sudah cukup
--     dijawab oleh kombinasi method dan alasan.
--   - Detail path tetap tersedia di log WARN untuk penelusuran satu peristiwa.
--
-- Satu baris mewakili satu menit, satu method, dan satu alasan. Jumlahnya
-- terbatas, sehingga operator bisa melihat lonjakan tanpa membuat tabel
-- membengkak.

CREATE TABLE security_rejection_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_start TIMESTAMP WITH TIME ZONE NOT NULL,
    http_method VARCHAR(16) NOT NULL,
    reason VARCHAR(64) NOT NULL,
    rejection_count BIGINT NOT NULL DEFAULT 0,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_security_rejection_stats UNIQUE (window_start, http_method, reason)
);

CREATE INDEX idx_security_rejection_stats_window_start
    ON security_rejection_stats(window_start);

COMMENT ON TABLE sessions IS
    'Sesi perangkat. Satu sesi menaungi banyak token refresh hasil rotasi';
COMMENT ON COLUMN refresh_tokens.session_id IS
    'Sesi pemilik token. NULL hanya untuk token yang terbit sebelum fitur sesi ada';
COMMENT ON TABLE security_rejection_stats IS
    'Agregat penolakan 401 per menit, method, dan alasan. Tanpa path dan tanpa alamat IP';
